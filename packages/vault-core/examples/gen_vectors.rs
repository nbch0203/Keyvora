//! Generates packages/shared-models/test-vectors/vault-v1.json — cross-platform vectors consumed by the Rust, WASM
//! (TypeScript), Kotlin and independent Python (argon2-cffi + OpenSSL) tests.
//!
//! Usage: cargo run -p keyvora-vault --example gen_vectors -- <output.json>

use base64::engine::general_purpose::STANDARD as B64;
use base64::Engine;
use keyvora_crypto::{derive_recovery_key, derive_wrapping_key, encrypt_with_nonce_for_tests, Argon2Params, SecretKey};
use keyvora_vault::{origin, EntryInput, UnlockedVault};
use serde_json::json;

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn main() {
    let out = std::env::args().nth(1).expect("output path");
    let master = "Contrase\u{00f1}a maestra de prueba \u{1F511}";
    let params = Argon2Params { memory_kib: 19 * 1024, iterations: 2, parallelism: 1 };

    // 1. Argon2id KEK vector
    let kdf_salt: Vec<u8> = (0u8..32).collect();
    let kek = derive_wrapping_key(master.as_bytes(), &kdf_salt, &params).unwrap();

    // 2. HKDF recovery vector
    let ikm: Vec<u8> = (100u8..132).collect();
    let rsalt: Vec<u8> = (200u8..232).collect();
    let rkek = derive_recovery_key(&ikm, &rsalt, keyvora_vault::container::RECOVERY_INFO).unwrap();

    // 3. AES-256-GCM vector
    let key = SecretKey::from_slice(&[0x42; 32]).unwrap();
    let nonce = [7u8; 12];
    let aad = b"keyvora.vault.v1.payload\0vector";
    let pt = "{\"hello\":\"mundo \u{00e9}\"}".as_bytes();
    let ct = encrypt_with_nonce_for_tests(&key, &nonce, aad, pt).unwrap();

    // 4. Full container
    let (mut v, rk) = UnlockedVault::create(master, params, "vector-device", 1_763_150_400_000).unwrap();
    let entries = [
        EntryInput {
            title: "GitHub".into(),
            username: "alice@example.com".into(),
            password: "gH#7kLp!2qRz@9vXw$Tn".into(),
            urls: vec!["https://github.com".into()],
            notes: "".into(),
        },
        EntryInput {
            title: "Banco \u{00d1}and\u{00fa}".into(),
            username: "alice".into(),
            password: "p\u{00e1}ss \u{4f60}\u{597d}".into(),
            urls: vec!["https://banco.example.es".into(), "androidapp://es.example.banco".into()],
            notes: "Notas\ncon salto".into(),
        },
    ];
    for (i, e) in entries.iter().enumerate() {
        v.create_entry(e.clone(), 1_763_150_400_000 + i as i64 * 1000).unwrap();
    }
    let container = v.export_container().unwrap();

    let matches: Vec<_> = [
        ("https://github.com", "https://github.com/login"),
        ("https://accounts.google.com", "https://mail.google.com"),
        ("https://github.com", "https://github.com.evil.com"),
        ("https://alice.github.io", "https://mallory.github.io"),
        ("https://paypal.com", "https://p\u{0430}ypal.com"),
        ("https://example.com", "http://example.com"),
        ("http://localhost:3000", "http://localhost:3000/x"),
        ("example.co.uk", "https://login.example.co.uk"),
    ]
    .iter()
    .map(|(e, p)| json!({ "entryUrl": e, "pageUrl": p, "expected": origin::match_level(e, p).as_str() }))
    .collect();

    let doc = json!({
        "description": "Keyvora cross-platform test vectors, format v1. Generated by packages/vault-core/examples/gen_vectors.rs",
        "argon2id": {
            "passwordUtf8": master, "saltHex": hex(&kdf_salt),
            "memoryKiB": params.memory_kib, "iterations": params.iterations, "parallelism": params.parallelism,
            "expectedKeyHex": hex(kek.expose())
        },
        "hkdfRecovery": {
            "ikmHex": hex(&ikm), "saltHex": hex(&rsalt), "info": String::from_utf8_lossy(keyvora_vault::container::RECOVERY_INFO),
            "expectedKeyHex": hex(rkek.expose())
        },
        "aes256gcm": {
            "keyHex": hex(key.expose()), "nonceHex": hex(&nonce), "aadHex": hex(aad), "plaintextHex": hex(pt),
            "expectedCiphertextHex": hex(&ct)
        },
        "vault": {
            "masterPassword": master,
            "masterPasswordNfdVariant": "Contrase\u{006e}\u{0303}a maestra de prueba \u{1F511}",
            "recoveryKey": rk.to_display().as_str(),
            "container": container,
            "expectedEntries": entries.iter().map(|e| json!({"title": e.title, "username": e.username, "password": e.password, "urls": e.urls, "notes": e.notes})).collect::<Vec<_>>(),
            "dataKeyB64": B64.encode(v.export_data_key().as_slice())
        },
        "originMatching": matches
    });
    std::fs::write(&out, serde_json::to_string_pretty(&doc).unwrap()).unwrap();
    println!("wrote {out}");
}
